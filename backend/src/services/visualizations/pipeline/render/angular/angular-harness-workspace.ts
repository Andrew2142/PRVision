async function writeAtomic(target: string, content: string): Promise<void> {
  const temp = `${target}.${randomBytes(4).toString("hex")}.tmp`;
  try {
    await fs.writeFile(temp, content, "utf8");
    await fs.rename(temp, target);
  } catch (error) {
    await fs.rm(temp, { force: true });
    throw error;
  }
}

/** Text of a file inside `root` (realpath-confined, at most `maxBytes`), or null. */
export async function readAngularConfinedText(root: string, file: string, maxBytes: number): Promise<string | null> {
  try {
    const [realRoot, realFile] = await Promise.all([fs.realpath(root), fs.realpath(file)]);
    if (!isPathInside(realRoot, realFile)) {
      return null;
    }
    const stat = await fs.stat(realFile);
    if (!stat.isFile() || stat.size > maxBytes) {
      return null;
    }
    return await fs.readFile(realFile, "utf8");
  } catch {
    return null;
  }
}

/** Installed major of a package as resolved from `fromDir` (follows the node_modules links), or null. */
export async function installedPackageMajor(fromDir: string, packageName: string): Promise<number | null> {
  try {
    const manifest = require.resolve(`${packageName}/package.json`, { paths: [fromDir] });
    const parsed: unknown = JSON.parse(await fs.readFile(manifest, "utf8"));
    const version = isRecord(parsed) && typeof parsed.version === "string" ? parsed.version : "";
    const major = Number.parseInt(version.split(".")[0] ?? "", 10);
    return Number.isFinite(major) ? major : null;
  } catch {
    return null;
  }
}

/**
 * Throws AngularTemplatesMissingError when one of the Angular templates is absent in `dir`.
 *
 * @param dir - The Angular templates directory (ANGULAR_HARNESS_TEMPLATES_DIR).
 */
export async function assertAngularTemplatesPresent(dir: string): Promise<void> {
  const files = [
    ...ANGULAR_TEMPLATE_FILES,
    ...SHARED_TEMPLATE_FILES.map((file) => path.join("..", SHARED_TEMPLATE_DIR_NAME, file))
  ];
  for (const file of files) {
    try {
      await fs.access(path.join(dir, file));
    } catch {
      throw new AngularTemplatesMissingError(
        "PRVision's Angular harness templates are missing (backend/harness-templates/angular). Reinstall PRVision."
      );
    }
  }
}

export interface AngularPrepareResult {
  warnings: string[];
  angularMajor: number | null;
  zone: boolean;
  animations: boolean;
  /** Workspace-relative tsconfig chain files (side-wide attribution). */
  tsconfigFiles: string[];
}

/** Writes the Angular harness folder of each side. */
export class AngularHarnessWorkspaceWriter {
  constructor(readonly templatesDir: string = ANGULAR_HARNESS_TEMPLATES_DIR) {}

  /**
   * mkdir -p, copy templates (overwrite), write `.gitignore`, `index.html`, `tsconfig.json` and
   * `framework.generated.ts`, and an empty registry.
   *
   * @param layout - The side layout.
   * @param project - The side's angular.json project.
   * @param configuration - Build configuration (index, tsConfig and polyfills are read from the merged options).
   */
  async prepareSide(
    layout: AngularSideLayout,
    project: AngularProjectInfo,
    configuration: string | null
  ): Promise<AngularPrepareResult> {
    const warnings: string[] = [];
    for (const dir of [layout.componentsDir, layout.mocksDir]) {
      assertAngularPathInside(layout.worktreeDir, dir);
      await fs.mkdir(dir, { recursive: true });
    }
    for (const file of ANGULAR_TEMPLATE_FILES) {
      await fs.copyFile(path.join(this.templatesDir, file), path.join(layout.harnessDir, file));
    }
    // 16 §7.5: the shared step runtime lives next to the React templates (<templates>/shared/).
    for (const file of SHARED_TEMPLATE_FILES) {
      await fs.copyFile(
        path.join(this.templatesDir, "..", SHARED_TEMPLATE_DIR_NAME, file),
        path.join(layout.harnessDir, file)
      );
    }
    await writeAtomic(path.join(layout.harnessDir, ".gitignore"), "*\n");

    const options = mergedTargetOptions(project.build, configuration);
    const indexInput = indexInputOf(options);
    let appIndex: string | null = null;
    if (indexInput !== null) {
      const indexFile = path.resolve(layout.workspaceRoot, indexInput);
      appIndex = isPathInside(layout.worktreeDir, indexFile)
        ? await readAngularConfinedText(layout.worktreeDir, indexFile, INDEX_MAX_BYTES)
        : null;
    }
    if (appIndex === null) {
      warnings.push(
        `The app's index.html could not be read on the ${layout.side} side; the harness page uses a minimal head.`
      );
    }
    await writeAtomic(path.join(layout.harnessDir, "index.html"), buildHarnessIndexHtml(appIndex));

    const tsConfigOption = typeof options.tsConfig === "string" ? options.tsConfig : "tsconfig.json";
    const targetTsconfig = path.resolve(layout.workspaceRoot, tsConfigOption);
    assertAngularPathInside(layout.worktreeDir, targetTsconfig);
    const dtsIncludes = (await effectiveDtsIncludes(targetTsconfig)).filter((entry) =>
      isPathInside(layout.worktreeDir, entry.replace(/\*.*$/, "") || layout.worktreeDir)
    );
    await writeAtomic(
      path.join(layout.harnessDir, "tsconfig.json"),
      buildHarnessTsconfig(layout.harnessDir, targetTsconfig, dtsIncludes)
    );
    const tsconfigFiles = (await tsconfigChain(targetTsconfig))
      .filter((file) => isPathInside(layout.workspaceRoot, file))
      .map((file) => toPosix(path.relative(layout.workspaceRoot, file)));

    const zone = usesZone(options);
    const angularMajor = await installedPackageMajor(layout.workspaceRoot, "@angular/core");
    const animations = (await installedPackageMajor(layout.workspaceRoot, "@angular/animations")) !== null;
    const framework = buildFrameworkSource({ zone, angularMajor, animations });
    if (framework.warning !== null) {
      warnings.push(framework.warning);
    }
    await writeAtomic(path.join(layout.harnessDir, "framework.generated.ts"), framework.source);
    await this.writeRegistry(layout, []);
    return { warnings, angularMajor, zone, animations, tsconfigFiles };
  }

  /** Writes components/<id>.ts (overwrites an earlier version, e.g. after repair). */
  async writeComponentHarness(layout: AngularSideLayout, componentId: number, harnessSource: string): Promise<string> {
    if (!Number.isInteger(componentId) || componentId <= 0) {
      throw new Error(`Invalid component id ${String(componentId)}`);
    }
    const target = path.join(layout.componentsDir, `${String(componentId)}.ts`);
    assertAngularPathInside(layout.harnessDir, target);
    await fs.mkdir(layout.componentsDir, { recursive: true });
    await writeAtomic(target, toAngularHarnessFileSource(harnessSource));
    return target;
  }

  /** Writes mocks/<hash>.ts. */
  async writeMock(layout: AngularSideLayout, hash: string, source: string): Promise<string> {
    if (!/^[0-9a-f]{8,64}$/.test(hash)) {
      throw new Error(`Invalid mock hash ${hash}`);
    }
    const target = path.join(layout.mocksDir, `${hash}.ts`);
    assertAngularPathInside(layout.harnessDir, target);
    await fs.mkdir(layout.mocksDir, { recursive: true });
    await writeAtomic(target, toAngularHarnessFileSource(source));
    return target;
  }

  /** Writes registry.generated.ts for the items of one build. */
  async writeRegistry(layout: AngularSideLayout, componentIds: readonly number[]): Promise<void> {
    await writeAtomic(path.join(layout.harnessDir, "registry.generated.ts"), buildRegistrySource(componentIds));
  }
}
