const BASE_STYLE = `  <style id="prvision-base-style">
    html, body { margin: 0; padding: 0; background: #ffffff; }
    #prvision-root { display: flow-root; box-sizing: border-box; width: 100%; min-height: 48px; padding: 0; }
  </style>`;

const MINIMAL_HEAD = `
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">`;

/**
 * Harness index.html (15 §5.7.5): the app index's `<head>` children with the title replaced, `<base>` dropped and
 * `<base href="/">` inserted, plus the base style block; the body is only `<prvision-root>`.
 *
 * @param appIndexHtml - The build target's index.html, or null when missing (minimal head).
 */
export function buildHarnessIndexHtml(appIndexHtml: string | null): string {
  const head = appIndexHtml === null ? MINIMAL_HEAD : (/<head[^>]*>([\s\S]*?)<\/head>/i.exec(appIndexHtml)?.[1] ?? "");
  const withoutBase = head.replace(/<base\b[^>]*>/gi, "");
  const titled = /<title\b[^>]*>[\s\S]*?<\/title>/i.test(withoutBase)
    ? withoutBase.replace(/<title\b[^>]*>[\s\S]*?<\/title>/i, "<title>PRVision harness</title>")
    : `${withoutBase}\n  <title>PRVision harness</title>`;
  const charset = /<meta\s+charset[^>]*>/i.exec(titled);
  const withBase =
    charset === null
      ? `\n  <base href="/">${titled}`
      : `${titled.slice(0, charset.index + charset[0].length)}\n  <base href="/">${titled.slice(
          charset.index + charset[0].length
        )}`;
  return `<!doctype html>
<html lang="en">
<head>${withBase.trimEnd()}
${BASE_STYLE}
</head>
<body>
  <prvision-root id="prvision-root"></prvision-root>
</body>
</html>
`;
}

/**
 * Harness tsconfig.json (15 §5.7.5): extends the build target's tsconfig, compiles only the harness import graph
 * (`files: ["./main.ts"]`) and keeps ambient `.d.ts` includes rebased to the harness folder.
 *
 * @param harnessDir - Absolute harness dir.
 * @param targetTsconfig - Absolute path of the build target's tsConfig.
 * @param dtsIncludes - Absolute (glob) paths of the effective `.d.ts` include entries.
 */
export function buildHarnessTsconfig(
  harnessDir: string,
  targetTsconfig: string,
  dtsIncludes: readonly string[]
): string {
  const relative = (target: string): string => {
    const rel = toPosix(path.relative(harnessDir, target));
    return rel.startsWith(".") ? rel : `./${rel}`;
  };
  return `${JSON.stringify(
    {
      extends: relative(targetTsconfig),
      compilerOptions: { outDir: "./out-tsc", noUnusedLocals: false, noUnusedParameters: false },
      files: ["./main.ts"],
      include: dtsIncludes.map(relative)
    },
    null,
    2
  )}\n`;
}

export interface FrameworkSourceInput {
  zone: boolean;
  /** Installed @angular/core major, or null when unknown (treated as the newest supported). */
  angularMajor: number | null;
  animations: boolean;
}

/**
 * framework.generated.ts (15 §5.7.5, §5.7.2 notes): zone or zoneless change detection, noop animations when
 * installed, and `FRAMEWORK_WHEN_STABLE` (whenStable on ≥ 18, the isStable observable on 17).
 *
 * @returns The source and a warning when zoneless was requested on Angular 17.
 */
export function buildFrameworkSource(input: FrameworkSourceInput): { source: string; warning: string | null } {
  const major = input.angularMajor ?? Number.MAX_SAFE_INTEGER;
  let detection = "provideZoneChangeDetection";
  let warning: string | null = null;
  if (!input.zone) {
    if (major >= 20) {
      detection = "provideZonelessChangeDetection";
    } else if (major >= 18) {
      detection = "provideExperimentalZonelessChangeDetection";
    } else {
      warning = "Zoneless change detection needs Angular 18 or newer; rendering with zone change detection.";
    }
  }
  const legacyStable = major < 18;
  const lines = [
    "// Generated by PRVision. Do not edit.",
    `import { ${detection}, type ApplicationRef, type EnvironmentProviders, type Provider } from '@angular/core';`
  ];
  if (input.animations) {
    lines.push("import { provideNoopAnimations } from '@angular/platform-browser/animations';");
  }
  if (legacyStable) {
    lines.push("import { firstValueFrom } from 'rxjs';", "import { filter } from 'rxjs/operators';");
  }
  lines.push(
    "",
    "export const FRAMEWORK_PROVIDERS: Array<Provider | EnvironmentProviders> = [",
    `  ${detection}(),`,
    ...(input.animations ? ["  provideNoopAnimations(),"] : []),
    "];",
    "",
    legacyStable
      ? "export const FRAMEWORK_WHEN_STABLE = (appRef: ApplicationRef): Promise<unknown> =>\n  firstValueFrom(appRef.isStable.pipe(filter(Boolean)));"
      : "export const FRAMEWORK_WHEN_STABLE = (appRef: ApplicationRef): Promise<unknown> => appRef.whenStable();",
    ""
  );
  return { source: lines.join("\n"), warning };
}

/** registry.generated.ts: lazy loaders for the harnesses of one build only. */
export function buildRegistrySource(componentIds: readonly number[]): string {
  const lines = [
    "// Generated by PRVision. Do not edit.",
    "export const HARNESS_LOADERS: Record<string, () => Promise<unknown>> = {"
  ];
  for (const id of [...componentIds].sort((a, b) => a - b)) {
    lines.push(`  '${String(id)}': () => import('./components/${String(id)}'),`);
  }
  lines.push("};", "");
  return lines.join("\n");
}

/** Harness or mock file content: `// @ts-nocheck` and the generated-by header, then the source. */
export function toAngularHarnessFileSource(source: string): string {
  return `${ANGULAR_GENERATED_HEADER}${source.endsWith("\n") ? source : `${source}\n`}`;
}

