/**
 * Angular harness workspace (15 §5.7.5): side layouts and the files written into
 * `<worktree>/<appRoot>/.prvision-harness/`: the static templates, `.gitignore`, the generated `index.html`,
 * `tsconfig.json`, `framework.generated.ts` and `registry.generated.ts`, harness modules and mock files.
 * Never writes outside the harness folder and never touches node_modules or tracked files.
 */
import { randomBytes } from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import ts from "typescript";
import { ANGULAR_HARNESS_TEMPLATES_DIR, HARNESS_DIR_NAME } from "../../../../../config-consts";
import { isPathInside } from "../../../../../utilities";
import { SHARED_TEMPLATE_DIR_NAME, SHARED_TEMPLATE_FILES } from "../harness-workspace";
import { isRecord, type RenderSide } from "../render-types";
import { indexInputOf, usesZone, type AngularProjectInfo, mergedTargetOptions } from "./angular-build-options";

export const ANGULAR_TEMPLATE_FILES = ["main.ts", "harness-api.ts", "http-backend.ts"] as const;
export const ANGULAR_GENERATED_HEADER = "// @ts-nocheck\n// Generated by PRVision for this render run. Do not edit.\n";
const INDEX_MAX_BYTES = 512 * 1024;
const TSCONFIG_MAX_BYTES = 1024 * 1024;
const EXTENDS_MAX_DEPTH = 10;

export interface AngularSideLayout {
  side: RenderSide;
  worktreeDir: string; // absolute
  workspaceRoot: string; // <worktree>/<appRoot> (holds angular.json); the build child's cwd
  harnessDir: string; // <workspaceRoot>/.prvision-harness
  componentsDir: string;
  mocksDir: string;
  distDir: string;
}

function toPosix(value: string): string {
  return value.split(path.sep).join("/");
}

/** Thrown when backend/harness-templates/angular (or one of its files) is missing. */
export class AngularTemplatesMissingError extends Error {
  override readonly name = "AngularTemplatesMissingError";
}

/**
 * Throws Error("Path escapes worktree: …") unless `child` is `parent` or inside it (after path.resolve). Same rule
 * as 10's guard; kept here because Angular code does not import the React harness workspace module (15 §5.3).
 */
export function assertAngularPathInside(parent: string, child: string): void {
  const relative = path.relative(path.resolve(parent), path.resolve(child));
  if (relative !== "" && (relative.startsWith("..") || path.isAbsolute(relative))) {
    throw new Error(`Path escapes worktree: ${child}`);
  }
}

/**
 * Replaces the single import/export module specifier equal to `from` by `to` (TypeScript AST, decorators allowed).
 * Used for the base side of a renamed component.
 *
 * @throws Error("target specifier not found exactly once") when the count is not 1.
 */
export function rewriteAngularTargetSpecifier(source: string, from: string, to: string): string {
  const sourceFile = ts.createSourceFile("harness.ts", source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  const hits: ts.StringLiteral[] = [];
  for (const statement of sourceFile.statements) {
    if (
      (ts.isImportDeclaration(statement) || ts.isExportDeclaration(statement)) &&
      statement.moduleSpecifier !== undefined &&
      ts.isStringLiteral(statement.moduleSpecifier) &&
      statement.moduleSpecifier.text === from
    ) {
      hits.push(statement.moduleSpecifier);
    }
  }
  const hit = hits[0];
  if (hits.length !== 1 || hit === undefined) {
    throw new Error("target specifier not found exactly once");
  }
  return `${source.slice(0, hit.getStart(sourceFile) + 1)}${to}${source.slice(hit.getEnd() - 1)}`;
}

/**
 * Computes the harness layout of one side.
 *
 * @throws Error("Path escapes worktree: …") when `appRoot` leaves the worktree.
 */
export function resolveAngularLayout(side: RenderSide, worktreeDir: string, appRoot: string): AngularSideLayout {
  const root = path.resolve(worktreeDir);
  const workspaceRoot = path.resolve(root, appRoot === "" ? "." : appRoot);
  assertAngularPathInside(root, workspaceRoot);
  const harnessDir = path.join(workspaceRoot, HARNESS_DIR_NAME);
  const layout: AngularSideLayout = {
    side,
    worktreeDir: root,
    workspaceRoot,
    harnessDir,
    componentsDir: path.join(harnessDir, "components"),
    mocksDir: path.join(harnessDir, "mocks"),
    distDir: path.join(harnessDir, "dist")
  };
  for (const dir of [layout.harnessDir, layout.componentsDir, layout.mocksDir, layout.distDir]) {
    assertAngularPathInside(root, dir);
  }
  return layout;
}

