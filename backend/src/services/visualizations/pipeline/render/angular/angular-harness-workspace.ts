interface ParsedTsconfig {
  include: string[] | null;
  extendsList: string[];
}

async function readTsconfig(file: string): Promise<ParsedTsconfig | null> {
  try {
    const stat = await fs.stat(file);
    if (!stat.isFile() || stat.size > TSCONFIG_MAX_BYTES) {
      return null;
    }
    const parsed = ts.parseConfigFileTextToJson(file, await fs.readFile(file, "utf8"));
    if (parsed.error !== undefined || !isRecord(parsed.config)) {
      return null;
    }
    const config = parsed.config;
    const include = Array.isArray(config.include)
      ? config.include.filter((entry): entry is string => typeof entry === "string")
      : null;
    const rawExtends: unknown = config.extends;
    const extendsList =
      typeof rawExtends === "string"
        ? [rawExtends]
        : Array.isArray(rawExtends)
          ? rawExtends.filter((entry): entry is string => typeof entry === "string")
          : [];
    return { include, extendsList };
  } catch {
    return null;
  }
}

function resolveExtends(fromFile: string, specifier: string): string | null {
  const dir = path.dirname(fromFile);
  if (specifier.startsWith(".") || path.isAbsolute(specifier)) {
    const target = path.resolve(dir, specifier);
    return target.endsWith(".json") ? target : `${target}.json`;
  }
  try {
    return require.resolve(specifier, { paths: [dir] });
  } catch {
    return null;
  }
}

/**
 * The `.d.ts` entries of the effective `include` of a tsconfig chain (the nearest config that declares `include`,
 * TypeScript semantics), as absolute glob paths.
 */
export async function effectiveDtsIncludes(tsconfigFile: string, depth = 0): Promise<string[]> {
  if (depth > EXTENDS_MAX_DEPTH) {
    return [];
  }
  const parsed = await readTsconfig(tsconfigFile);
  if (parsed === null) {
    return [];
  }
  if (parsed.include !== null) {
    return parsed.include
      .filter((entry) => entry.endsWith(".d.ts"))
      .map((entry) => path.resolve(path.dirname(tsconfigFile), entry));
  }
  for (const specifier of [...parsed.extendsList].reverse()) {
    const target = resolveExtends(tsconfigFile, specifier);
    if (target === null) {
      continue;
    }
    const found = await readTsconfig(target);
    if (found === null) {
      continue;
    }
    const nested = await effectiveDtsIncludes(target, depth + 1);
    if (nested.length > 0 || found.include !== null) {
      return nested;
    }
  }
  return [];
}

/** Every tsconfig file of the chain (workspace-relative, for side-wide error attribution). */
export async function tsconfigChain(tsconfigFile: string, depth = 0): Promise<string[]> {
  if (depth > EXTENDS_MAX_DEPTH) {
    return [];
  }
  const parsed = await readTsconfig(tsconfigFile);
  if (parsed === null) {
    return [];
  }
  const chain = [tsconfigFile];
  for (const specifier of parsed.extendsList) {
    const target = resolveExtends(tsconfigFile, specifier);
    if (target !== null) {
      chain.push(...(await tsconfigChain(target, depth + 1)));
    }
  }
  return chain;
}

