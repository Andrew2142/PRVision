/**
 * Generates backend/src/models/* from src/database/schema.ts (03 §9.1).
 *
 * Copied from Uply-v2 backend/scripts/generate-models.ts and adapted: nullable columns are typed `T | null`,
 * jsonb columns take their type from JSON_COLUMN_TYPES (a missing entry is an error), the constructor is
 * lint-clean under strictTypeChecked, and every file is formatted in memory with Prettier so `models:drift`
 * is stable.
 */
import fs from "node:fs";
import path from "node:path";
import { Table as DrizzleTable, getTableColumns, getTableName } from "drizzle-orm";
import * as prettier from "prettier";
import * as schema from "../src/database/schema";

/** The subset of a Drizzle column the generator reads. Exported so tests can pass fake columns. */
export interface ColumnMetadata {
  dataType?: string;
  enumValues?: readonly string[] | undefined;
  notNull?: boolean;
  getSQLType?: () => string;
}

/** One generated field. `tsType` excludes `| null`; `nullable` adds it. */
export interface ColumnDefinition {
  name: string;
  tsType: string;
  nullable: boolean;
  typeImports: string[];
  /** Module `typeImports` come from (relative to src/models); null when there are none. */
  typesModule: string | null;
}

/** One generated model class. */
export interface TableDefinition {
  exportName: string;
  tableName: string;
  className: string;
  columns: ColumnDefinition[];
}

/** TS type of a mapped column plus the type names it needs and the module they come from. */
export interface MappedColumnType {
  tsType: string;
  typeImports: string[];
  /** Module `typeImports` come from (relative to src/models); null when there are none. */
  typesModule: string | null;
}

/** Export name → class name, for tables whose singular form the heuristic gets wrong. Empty for PRVision v1. */
const CLASS_NAME_OVERRIDES: Record<string, string> = {};

