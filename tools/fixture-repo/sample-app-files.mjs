/** Returns `source` with `search` replaced exactly once; throws if `search` does not occur exactly once. */
function replaceOnce(source, search, replacement) {
  const first = source.indexOf(search);
  if (first === -1 || source.indexOf(search, first + search.length) !== -1) {
    throw new Error(`sample-app-files: expected exactly one occurrence of ${JSON.stringify(search)}`);
  }
  return source.slice(0, first) + replacement + source.slice(first + search.length);
}

